import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");

function sqlText(value) {
  if (value == null || value === "") return "null";
  return `'${String(value).replaceAll("'", "''")}'`;
}

function sqlArray(values) {
  if (!values || values.length === 0) return "array[]::text[]";
  return `array[${values.map((value) => sqlText(value)).join(", ")}]::text[]`;
}

export function buildSeed() {
  const reports = JSON.parse(readFileSync(resolve(root, "src/data/reports.json"), "utf8"));
  const weekly = JSON.parse(readFileSync(resolve(root, "src/data/weekly-5-5.json"), "utf8"));
  const reportRows = reports.map((report) => {
    const tickers = `array[${report.tickers.map((ticker) => sqlText(ticker)).join(", ")}]::text[]`;
    return `(${[
      sqlText(report.slug),
      sqlText(report.title),
      sqlText(report.ticker),
      tickers,
      sqlText(report.industry),
      sqlText(report.direction),
      sqlText(report.published),
      sqlText(report.pdfPath),
      sqlText(report.pdfFilename),
      sqlText(report.href),
    ].join(", ")})`;
  });

  const weekRows = [];
  for (const week of weekly.weeks) {
    for (const side of ["long", "short"]) {
      (week[side] || []).forEach((item, index) => {
        weekRows.push(`(${[
          sqlText(week.weekOf),
          sqlText(side),
          String(index + 1),
          sqlText(item.sector),
          sqlText(item.etf || null),
          sqlArray(item.tickers),
          sqlText(item.thesis),
          sqlText(item.report || null),
          week.example ? "true" : "false",
        ].join(", ")})`);
      });
    }
  }

  return `-- Generated from src/data/reports.json and src/data/weekly-5-5.json.
-- Edit those files, then run npm run db:seed. Do not edit this file by hand.

delete from public.weekly_5_5;
delete from public.reports;

insert into public.reports (
  slug, title, ticker, tickers, industry, direction, published_on, pdf_path, pdf_filename, href
) values
${reportRows.join(",\n")};

insert into public.weekly_5_5 (
  week_of, side, position, sector, etf, tickers, thesis, report_href, example
) values
${weekRows.join(",\n")};
`;
}

const target = resolve(root, "supabase/seed.sql");
if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  writeFileSync(target, buildSeed());
}
